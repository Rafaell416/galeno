/// Escribe el hook `PreToolUse` que exige confirmación en los envíos externos.
///
/// El `matcher` del hook, que vive en `settings.json`, ya limita a qué
/// herramientas se aplica (las de Slack y Gmail que no son lecturas conocidas:
/// `SettingsRenderer.approvalMatcher`), así que el script no necesita leer ni parsear la
/// entrada: siempre responde pidiendo confirmación. Eso lo deja sin ninguna
/// dependencia — nada de `jq`, que no está en todos los Mac.
///
/// Es la segunda capa: la regla `ask` de `settings.json` ya pregunta. El hook
/// está para que la decisión siga en pie si alguien afloja los permisos.
enum ApprovalHookRenderer {
    /// El hook que, **en la app de Claude (escritorio)**, deja pasar sin preguntar las lecturas de los
    /// conectores de la cuenta (`SettingsRenderer.connectorReadsMatcher`). En Terminal eso lo hacen
    /// las reglas `allow`, y este hook no llega a dispararse. Igual que el otro: el `matcher` decide a
    /// qué se aplica y el script no lee la entrada.
    static func renderConnectorReads(language: Language) -> String {
        let comment =
            switch language {
            case .spanish:
                """
                # Deja leer sin preguntar por los conectores de tu cuenta de Claude (Gmail,
                # Calendar, Drive, Docs, Sheets) en la app de Claude, donde sus herramientas
                # llevan otro nombre y las reglas de permiso no coinciden.
                #
                # El matcher de settings.json lo limita a las herramientas que solo leen.
                # Enviar, escribir o compartir nunca pasa por aquí.
                #
                # Lo genera Galeno.
                """
            case .english:
                """
                # Lets the agent read through your Claude account's connectors (Gmail,
                # Calendar, Drive, Docs, Sheets) without asking in the Claude app, where their
                # tools carry a different name and the permission rules do not match.
                #
                # The matcher in settings.json limits it to the tools that only read.
                # Sending, writing or sharing never goes through here.
                #
                # Generated by Galeno.
                """
            }

        return """
            #!/bin/bash
            \(comment)
            cat <<'JSON'
            {
              "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "allow",
                "permissionDecisionReason": "Galeno: read-only connector tool"
              }
            }
            JSON

            """
    }

    static func render(language: Language) -> String {
        let reason =
            switch language {
            case .spanish:
                "Esto envía o cambia algo que ven otras personas. Revisa el destinatario y el contenido antes de aprobar."
            case .english:
                "This sends or changes something other people see. Check the recipient and the content before approving."
            }

        let comment =
            switch language {
            case .spanish:
                """
                # Exige confirmación humana antes de cualquier envío externo.
                #
                # El matcher de settings.json ya limita este hook a las herramientas
                # de Slack y Gmail que envían o escriben (leer no pasa por aquí), así
                # que no hace falta leer la entrada: siempre pedimos confirmación.
                # Sin dependencias a propósito.
                #
                # Lo genera Galeno. Si lo editas, el agente podrá enviar sin preguntar.
                """
            case .english:
                """
                # Requires human confirmation before any external send.
                #
                # The matcher in settings.json already limits this hook to the Slack
                # and Gmail tools that send or write (reading never gets here), so
                # there is no need to read the input: we always ask.
                # Deliberately dependency-free.
                #
                # Generated by Galeno. If you edit this, the agent may send without asking.
                """
            }

        return """
            #!/bin/bash
            \(comment)
            cat <<'JSON'
            {
              "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "ask",
                "permissionDecisionReason": "\(reason)"
              }
            }
            JSON

            """
    }
}
